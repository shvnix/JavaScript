//A variable is a named place to store a value.
// Imagine a box labeled age. You can store the number 20 inside it and use that value later.

let age = 20;
console.log(age);

/// here 'let' use to declare the variable 'age' is the name of the variable and 20 is the value of variable 
/// there's two type of to declare the variables 'let' and 'const'

// let
let name = 'amit'; //it can be reassigned
console.log(name);
name = 'sumit';
console.log(name);

// const
const id = 5; // cannot be reassigned
// id = 7; // error
console.log(id);

// var
var a = 8; // An older way to declare variables; usually avoid it in modern JavaScript
